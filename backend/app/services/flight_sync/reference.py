# 국내선: 제주 노선은 조금 길고 나머지는 대부분 1시간 안팎
_DOMESTIC_JEJU = Route(65, 45_000, 85_000, 2.0)
_DOMESTIC_OTHER = Route(55, 38_000, 75_000, 1.8)


def place_of(code: str) -> Place | None:
    return KOREA.get(code) or INTL_PLACES.get(code)


def is_korean(code: str) -> bool:
    return code in KOREA


def route_of(origin: str, dest: str) -> Route | None:
    """한국 공항이 한쪽 이상 끼어 있는 노선만 기준표가 있다."""
    if is_korean(origin) and is_korean(dest):
        return _DOMESTIC_JEJU if "CJU" in (origin, dest) else _DOMESTIC_OTHER
    if is_korean(origin):
        return INTL_ROUTES.get(dest)
    if is_korean(dest):
        return INTL_ROUTES.get(origin)
    return None
